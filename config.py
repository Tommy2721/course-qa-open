"""集中配置：所有可调参数都在这里，方便做对比实验时改一处、全项目生效。"""

import os
from pathlib import Path

# ---------- 国内网络适配（必须在导入 sentence-transformers 之前生效）----------
# 1) 走 HuggingFace 镜像下载模型
os.environ.setdefault("HF_ENDPOINT", "https://hf-mirror.com")
# 2) 禁用 Xet 存储后端。新版 huggingface-hub 会走 cas-bridge.xethub.hf.co，
#    这个地址不被镜像代理，会返回 403 Forbidden。禁用后回退到经典下载通道。
os.environ.setdefault("HF_HUB_DISABLE_XET", "1")

ROOT = Path(__file__).resolve().parent


# ---------- 路径 ----------
DATA_RAW = ROOT / "data" / "raw"          # 放原始课件
DATA_INDEX = ROOT / "data" / "index"      # 索引持久化目录
# 本地隐私过滤规则（一行一条关键词）。比赛要求材料中不得出现学校/教师信息，
# 老师给的课件首页常带这些，建索引前自动剔除含关键词的页。
# ⚠️ 这个文件放 data/ 下，已被 .gitignore 排除——规则本身含学校信息，绝不进仓库。
PRIVATE_FILTER_FILE = DATA_INDEX.parent / "private_filter.txt"
EVAL_DIR = ROOT / "eval"
EVAL_FILE = EVAL_DIR / "questions.jsonl"  # 评测集（由 questions.example.jsonl 复制改名）
PROFILE_FILE = DATA_INDEX / "profile.json"

# ---------- 开源模型 ----------
LLM_MODEL = "qwen2.5:7b-instruct"        # Ollama 模型名，显存不够可换成 qwen2.5:3b-instruct
EMBED_MODEL = "BAAI/bge-m3"              # 向量模型
RERANK_MODEL = "BAAI/bge-reranker-v2-m3"  # 重排模型

# ---------- 分块参数（★ 自研点 1：这些参数要用实验说话）----------
CHUNK_MAX_CHARS = 700   # 每块最大字符数
CHUNK_OVERLAP = 80      # 相邻块重叠字符数
CHUNK_MIN_CHARS = 120   # 小于这个长度的块直接并入上一块，避免产生碎片

# ---------- 检索参数（★ 自研点 2）----------
TOP_K_VECTOR = 20       # 向量召回条数
TOP_K_BM25 = 20         # 关键词召回条数
TOP_K_FINAL = 5         # 最终送给大模型的条数
RRF_K = 60              # RRF 融合常数，越小越偏向排名靠前的结果

# ---------- 查询扩展（★ 自研点 5）----------
# 学生提问用口语，课件写的是书面术语，两者词面往往对不上。
# 开启后先用本地大模型把问题改写成多个检索式，分别召回再融合，
# 显著提升"条件题、对比题"这类词面不一致问题的召回率。
# 代价是每次问答多一次模型调用（约 1–3 秒），演示时可按需开关。
USE_QUERY_EXPANSION = False
QUERY_EXPANSION_N = 3      # 额外生成几个改写查询

# ---------- 小到大检索（★ 自研点 6）----------
# 用细粒度的块做检索（准），命中后把它所在的整个章节拼成上下文送给大模型（全）。
# 这样既不因为块太大而稀释相关性，也不因为块太小而缺少必要的上下文。
USE_PARENT_EXPANSION = True
PARENT_MAX_CHARS = 2500    # 单个命中扩展后的上下文上限，防止某章过长撑爆提示词

# ---------- 去冗余（★ 自研点 7）----------
# 章节内的相邻块内容高度重叠，Top-5 可能全是同一段话的不同切法，白白浪费上下文预算。
#
# ⚠️ 这里踩过一次坑，记录如下：
#   最初把 MMR 接在重排之后、用来重新挑选 Top-5，结果 MRR 从 0.950 掉到 0.942——
#   它为了多样性把最相关的那条往后挤了。
#   后来想明白：MMR 的价值是"给大模型省上下文预算"，不该去动引用排序。
#   而且小到大检索（USE_PARENT_EXPANSION）已经把同章节的块合并成同一段上下文，
#   同一章节的重复块天然就只占一份预算，MMR 在这里是多余的。
#   现在的做法：检索排序保持纯相关性，去冗余放到 build_context 里按章节去重（零成本）。
#   这个开关保留下来是为了做消融实验——如果你们的语料上 MMR 确实有正收益，可以打开。
USE_MMR = False
MMR_LAMBDA = 0.7           # 1.0 = 只看相关性；0.0 = 只看多样性；0.7 偏相关性
MMR_CANDIDATES = 15        # 重排后取多少条进入 MMR 挑选

# ---------- 答案自检（★ 自研点 8：抗幻觉，本作品的核心创新）----------
# 生成答案后，把答案拆成一条条"断言"，逐条回检索到的原文里找支持句。
# 找不到支持的断言会被标记出来——这样"引用"从装饰变成了可核查的事实依据。
#
# 为什么这是必要的：模型标注了 [1] 并不代表这句话真的被原文支持。
# "答案带出处"和"答案内容被出处支持"是两件事，后者才是可验证性。
USE_SELF_CHECK = True
VERIFY_CANDIDATES = 5      # 每条断言先用向量粗筛出几个候选句，再精算（两阶段，快）
VERIFY_MIN_SENT_CHARS = 8  # 太短的句子不作为证据候选
# 断言与证据句的匹配阈值（0~1）。留空则沿用 MIN_RERANK_SCORE。
# 该阈值偏保守会更安全（宁可多标几条"未直接支持"，也不要漏标）。
VERIFY_THRESHOLD = None

# ---------- 核验后的自动修订（把"标记问题"升级为"解决问题"）----------
# 核验发现无依据结论时，把无依据结论连同课件依据喂回大模型，
# 要求只修订这些结论（删除或改写为与依据一致），再复验一遍；
# 只有修订后无依据数下降才采纳，避免越改越差。
# 这构成"生成 → 核验 → 修订 → 复验"的完整闭环，限一次迭代以控制延迟。
USE_SELF_REVISION = True

# ---------- 拒答阈值（★ 自研点 3：必须用评测集校准，别拍脑袋）----------
# 这个分数是重排模型输出的相关性"概率"（0~1）。
# 当前值来自《第六章 树和二叉树》全 5 讲 PPT 的校准（2026-10-02，23 道评测题）：
#   可回答题与无答案题的分数在 0.44~0.46 区间犬牙交错（重叠无法靠单阈值消除），
#   因此取 0.44 保证贴线的可回答题不被误拒，让"图的遍历"这类
#   分数偏高但内容确实缺失的问题交由答案级拒答检测（第二级）兜底——实测有效。
# 对比记录：公式图片版 PDF 空隙 0.06；原始 PPT 校准后整体分布更健康。
# ⚠️ 每次更换/增加课件后必须重新校准：python -m src.eval --calibrate
MIN_RERANK_SCORE = 0.44

# ---------- 生成参数 ----------
TEMPERATURE = 0.1        # 知识问答要稳定，不要发散
MAX_CONTEXT_CHARS = 6000  # 拼进提示词的上下文上限，防止超长
